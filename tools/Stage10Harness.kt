import java.io.File
fun main(args: Array<String>) {
    val root = File(args.firstOrNull() ?: ".")
    var pass = 0; var fail = 0
    fun text(path:String)=File(root,path).readText()
    fun check(name:String, ok:Boolean){ println("${if(ok) "PASS" else "FAIL"} | $name"); if(ok) pass++ else fail++ }
    fun occurrences(h:String, n:String):Int { var i=0; var c=0; while(true){ i=h.indexOf(n,i); if(i<0) return c; c++; i+=n.length } }
    val top=text("build.gradle.kts")
    val app=text("app/build.gradle.kts")
    val identity=text("app/src/main/java/pro/noodle/mobile/core/version/BuildIdentity.kt")
    val ci=text("tools/ci-android-build.sh")
    val apk=text("tools/verify-apk.sh")
    val testApk=text("tools/verify-test-apk.sh")
    val wf=text(".github/workflows/android-ci.yml")
    val props=text("gradle.properties")
    check("alpha10 app identity", "versionCode = 100010" in app && "versionName = \"0.10.0-alpha10\"" in app)
    check("alpha10 runtime identity", "VERSION_CODE = 100010" in identity && "VERSION_NAME = \"0.10.0-alpha10\"" in identity)
    check("SNP compatibility remains 1.9.0", "SNP_COMPATIBILITY_VERSION = \"1.9.0\"" in identity)
    check("AGP built-in Kotlin no android plugin", "org.jetbrains.kotlin.android" !in top && "org.jetbrains.kotlin.android" !in app)
    check("KGP override present", "kotlin-gradle-plugin:2.4.10" in top)
    check("KSP runtime override present", "symbol-processing-gradle-plugin:2.3.11" in top)
    check("KSP plugin 2.3.11", "id(\"com.google.devtools.ksp\") version \"2.3.11\"" in top)
    check("Compose plugin matches Kotlin", "id(\"org.jetbrains.kotlin.plugin.compose\") version \"2.4.10\"" in top)
    check("Java target 17", "JavaVersion.VERSION_17" in app)
    check("Configuration cache enabled", "org.gradle.configuration-cache=true" in props)
    check("Warnings visible", "org.gradle.warning.mode=all" in props)
    check("Unit test phase first", ci.indexOf("01-testDebugUnitTest") < ci.indexOf("02-lintDebug"))
    check("Lint before assemble", ci.indexOf("02-lintDebug") < ci.indexOf("03-assembleDebug"))
    check("APK verification before androidTest build", ci.indexOf("04-verify-apk") < ci.indexOf("05-assembleDebugAndroidTest"))
    check("androidTest APK verified", "verify-test-apk.sh" in ci && "06-verify-androidTest-apk" in ci)
    check("Connected test conditional", "adb get-state" in ci && "connectedDebugAndroidTest" in ci)
    check("Main APK exact identity", "versionCode='100010' versionName='0.10.0-alpha10'" in apk)
    check("Main APK minSdk 28", "sdkVersion:'28'" in apk)
    check("Main APK targetSdk 37", "targetSdkVersion:'37'" in apk)
    check("Main APK requires DEX", "classes[0-9]*\\.dex" in apk)
    check("Main APK requires resources", "resources.arsc" in apk)
    check("Test APK package certified", "package: name='pro.noodle.mobile.test'" in testApk)
    check("Test APK targetSdk certified", "targetSdkVersion:'37'" in testApk)
    check("CI preserves failure logs", "if: always()" in wf && "build-certification/**" in wf)
    check("CI publishes APK only on success", "if: success()" in wf && "first-test-apk" in wf)
    check("Stable Media3 1.10.1", app.contains("media3-exoplayer:1.10.1") && !app.contains(":1.11.0"))
    check("Compose stable BOM", occurrences(app, "compose-bom:2026.06.00") == 2)
    println("RESULT | pass=$pass fail=$fail total=${pass+fail}")
    if(fail>0) error("Stage10 harness failed")
}
