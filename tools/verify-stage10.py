#!/usr/bin/env python3
from pathlib import Path
import sys
R=Path(__file__).resolve().parent.parent
C=[]
def rd(p): return (R/p).read_text()
def ck(n,v): C.append((n,bool(v)))
top=rd('build.gradle.kts'); app=rd('app/build.gradle.kts'); ci=rd('tools/ci-android-build.sh'); main=rd('tools/verify-apk.sh'); test=rd('tools/verify-test-apk.sh'); wf=rd('.github/workflows/android-ci.yml'); manifest=rd('app/src/main/AndroidManifest.xml')
ck('AGP 9.3.1','id("com.android.application") version "9.3.1"' in top)
ck('KGP 2.4.10 runtime override','classpath("org.jetbrains.kotlin:kotlin-gradle-plugin:2.4.10")' in top)
ck('KSP 2.3.11 runtime override','classpath("com.google.devtools.ksp:symbol-processing-gradle-plugin:2.3.11")' in top)
ck('KSP 2.3.11 plugin','id("com.google.devtools.ksp") version "2.3.11"' in top)
ck('built-in Kotlin retained','org.jetbrains.kotlin.android' not in top+app)
ck('compileSdk 37','compileSdk = 37' in app); ck('targetSdk 37','targetSdk = 37' in app); ck('minSdk 28','minSdk = 28' in app)
ck('Media3 stable only',app.count(':1.10.1') >= 7 and ':1.11.0' not in app)
ck('Room 2.8.4','val roomVersion = "2.8.4"' in app)
ck('DataStore 1.2.1','datastore-preferences:1.2.1' in app)
ck('Work 2.11.2','work-runtime-ktx:2.11.2' in app)
ck('WebKit 1.16.0','webkit:1.16.0' in app)
ck('Compose BOM 2026.06.00',app.count('compose-bom:2026.06.00')==2)
ck('sequential unit/lint/build',ci.index('01-testDebugUnitTest') < ci.index('02-lintDebug') < ci.index('03-assembleDebug'))
ck('main APK verifier called','verify-apk.sh' in ci and '04-verify-apk.log' in ci)
ck('androidTest built',':app:assembleDebugAndroidTest' in ci)
ck('androidTest verifier called','verify-test-apk.sh' in ci)
ck('connected tests conditional','adb get-state' in ci and ':app:connectedDebugAndroidTest' in ci)
ck('main identity certificate',"package: name='pro.noodle.mobile' versionCode='100010' versionName='0.10.0-alpha10'" in main)
ck('main SDK certificate',"sdkVersion:'28'" in main and "targetSdkVersion:'37'" in main)
ck('main structural certificate','classes[0-9]*\\.dex' in main and 'resources.arsc' in main and 'unzip -t' in main)
ck('test identity certificate',"package: name='pro.noodle.mobile.test'" in test and "targetSdkVersion:'37'" in test)
ck('foreground download permissions','android.permission.FOREGROUND_SERVICE_DATA_SYNC' in manifest)
ck('DownloadService restart manifest','androidx.media3.exoplayer.downloadService.action.RESTART' in manifest)
ck('failure logs uploaded','if: always()' in wf and 'build-certification/**' in wf)
ck('APK uploaded only on success','if: success()' in wf and 'first-test-apk' in wf)
ck('certification handoff exists',(R/'FIRST_TEST_APK_CERTIFICATION.md').is_file())
for n,v in C: print(('PASS' if v else 'FAIL')+' | '+n)
f=[n for n,v in C if not v]; print(f'RESULT | pass={len(C)-len(f)} fail={len(f)} total={len(C)}'); sys.exit(1 if f else 0)
